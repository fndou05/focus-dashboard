package com.frankondou.focus.service;

import com.frankondou.focus.entity.GradeCutoff;
import com.frankondou.focus.entity.User;
import com.frankondou.focus.exception.BadRequestException;
import com.frankondou.focus.repository.GradeCutoffRepository;
import com.frankondou.focus.repository.UserRepository;
import org.junit.jupiter.api.Test;

import java.math.BigDecimal;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.*;

class GradeCutoffServiceImplTest {

    private final GradeCutoffRepository gradeCutoffRepository = mock(GradeCutoffRepository.class);
    private final UserRepository userRepository = mock(UserRepository.class);
    private final GradeCutoffServiceImpl service =
            new GradeCutoffServiceImpl(gradeCutoffRepository, userRepository);

    @Test
    void updateGradeCutoff_raisingLowestCutoffAboveZero_throwsBadRequest() {
        User user = new User("a@b.com", "Franko", "America/New_York");
        GradeCutoff a = new GradeCutoff(user, "A", new BigDecimal("93"), new BigDecimal("4.0"));
        GradeCutoff f = new GradeCutoff(user, "F", BigDecimal.ZERO, BigDecimal.ZERO);
        UUID fId = UUID.randomUUID();
        // Ids are generated by the database, so the mocks fake them
        GradeCutoff spyF = spy(f);
        doReturn(fId).when(spyF).getId();
        GradeCutoff spyA = spy(a);
        doReturn(UUID.randomUUID()).when(spyA).getId();
        when(gradeCutoffRepository.findById(fId)).thenReturn(Optional.of(spyF));
        when(gradeCutoffRepository.findByUser_IdOrderByMinPercentDesc(any())).thenReturn(List.of(spyA, spyF));

        GradeCutoff updates = new GradeCutoff(null, null, new BigDecimal("50"), null);

        assertThrows(BadRequestException.class, () -> service.updateGradeCutoff(fId, updates));
        verify(gradeCutoffRepository, never()).save(any());
    }
}
